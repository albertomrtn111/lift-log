import assert from 'node:assert/strict'
const { chromium } = await import(process.env.CARDIO_PLAYWRIGHT_MODULE ?? 'playwright')
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 375, height: 812 }, isMobile: true, hasTouch: true })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(process.env.CARDIO_PREVIEW_URL ?? 'http://127.0.0.1:4186')
  assert.equal(await page.evaluate(() => {
    const ids = [...document.querySelectorAll('[id]')].map(element => element.id)
    return new Set(ids).size === ids.length
  }), true)
  await page.locator('form:visible').getByLabel('Nombre de la sesión').fill('Series de prueba')
  await page.locator('form:visible').getByLabel('Detalles del entrenamiento').fill('40 min suaves')
  await page.getByRole('button', { name: 'Guardar sesión', exact: true }).click()
  const saved = async () => JSON.parse(await page.getByLabel('Sesión guardada').textContent())
  assert.equal((await saved()).structure.mode, 'free_text')
  await page.getByRole('radio', { name: /Configuración estructurada/ }).click()
  await page.getByRole('button', { name: 'Calentamiento', exact: true }).click()
  let warmup = page.getByRole('group', { name: '1. Calentamiento', exact: true })
  await warmup.getByLabel('Distancia (km)', { exact: true }).fill('2')
  await warmup.getByLabel('Duración (min)', { exact: true }).fill('12')
  await page.getByRole('button', { name: 'Series', exact: true }).click()
  let intervals = page.getByRole('group', { name: '2. Bloque principal', exact: true })
  await intervals.getByLabel('Repeticiones', { exact: true }).fill('4')
  await intervals.getByLabel('Distancia por repetición (km)', { exact: true }).fill('1')
  await intervals.getByLabel('Duración por repetición (min)', { exact: true }).fill('4')
  await intervals.getByLabel('Tiempo por recuperación (min)', { exact: true }).fill('1.5')
  await intervals.getByLabel('Distancia por recuperación (km)', { exact: true }).fill('0.25')
  await page.getByRole('button', { name: 'Enfriamiento', exact: true }).click()
  let cooldown = page.getByRole('group', { name: '3. Vuelta a la calma', exact: true })
  await cooldown.getByLabel('Distancia (km)', { exact: true }).fill('1')
  await cooldown.getByLabel('Duración (min)', { exact: true }).fill('6')
  assert.equal(await page.locator('form:visible').getByLabel('Distancia (km)', { exact: true }).first().inputValue(), '7.75')
  await intervals.getByLabel('Incluir recuperación tras la última repetición').check()
  assert.equal(await page.locator('form:visible').getByLabel('Distancia (km)', { exact: true }).first().inputValue(), '8')
  await page.getByRole('button', { name: 'Guardar sesión', exact: true }).click()
  assert.equal((await saved()).targetDistanceKm, 8)
  assert.equal((await saved()).targetDurationMin, 40)
  assert.equal((await saved()).name, 'Series de prueba')
  await page.getByRole('button', { name: 'Reabrir sesión guardada' }).click()
  intervals = page.getByRole('group', { name: '2. Bloque principal', exact: true })
  assert.equal(await intervals.getByLabel('Incluir recuperación tras la última repetición').isChecked(), true)
  await intervals.getByLabel('Incluir recuperación tras la última repetición').uncheck()
  await page.getByRole('button', { name: 'Guardar sesión', exact: true }).click()
  assert.equal((await saved()).targetDistanceKm, 7.75)
  assert.equal((await saved()).targetDurationMin, 38.5)
  await intervals.getByLabel('Distancia por recuperación (km)', { exact: true }).fill('')
  assert.equal(await page.getByText('7 km contabilizados · parcial', { exact: true }).count(), 1)
  await page.getByRole('button', { name: 'Guardar sesión', exact: true }).click()
  assert.equal((await saved()).targetDistanceKm, undefined)
  await intervals.getByLabel('Tipo de recuperación').selectOption('passive')
  assert.equal(await page.locator('form:visible').getByLabel('Distancia (km)', { exact: true }).first().inputValue(), '7')
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
  await intervals.getByLabel('Tipo de recuperación').selectOption('active')
  await intervals.getByLabel('Distancia por recuperación (km)', { exact: true }).fill('0.25')
  await intervals.scrollIntoViewIfNeeded()
  await page.screenshot({ path: process.env.CARDIO_SCREENSHOT ?? '/tmp/nexttrain-cardio-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1280, height: 900 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
  await page.goto(process.env.CARDIO_PREVIEW_URL ?? 'http://127.0.0.1:4186')
  await page.setViewportSize({ width: 375, height: 812 })
  await page.locator('form:visible').getByText('Natación', { exact: true }).click()
  await page.getByRole('radio', { name: /Configuración estructurada/ }).click()
  await page.getByRole('button', { name: 'Series', exact: true }).click()
  intervals = page.getByRole('group', { name: '1. Bloque principal', exact: true })
  await intervals.getByLabel('Repeticiones', { exact: true }).fill('4')
  await intervals.getByLabel('Distancia por repetición (m)', { exact: true }).fill('200')
  await intervals.getByLabel('Duración por repetición (min)', { exact: true }).fill('4')
  await intervals.getByLabel('Tiempo por recuperación (min)', { exact: true }).fill('0.5')
  assert.equal(await page.locator('form:visible').getByLabel('Distancia (m)', { exact: true }).inputValue(), '800')
  await page.getByRole('button', { name: 'Guardar sesión', exact: true }).click()
  assert.equal((await saved()).targetDistanceKm, 0.8)
  assert.equal((await saved()).targetDurationMin, 17.5)
  assert.equal((await saved()).structure.trainingType, 'swim')
  await page.getByRole('button', { name: 'Reabrir sesión guardada' }).click()
  intervals = page.getByRole('group', { name: '1. Bloque principal', exact: true })
  assert.equal(await intervals.getByLabel('Distancia por repetición (m)', { exact: true }).inputValue(), '200')
  await intervals.getByLabel('Tipo de recuperación').selectOption('active')
  assert.equal(await page.getByText('800 m contabilizados · parcial', { exact: true }).count(), 1)
  await intervals.getByLabel('Ritmo de recuperación (/100 m)', { exact: true }).fill('2:30/100 m')
  assert.equal(await page.locator('form:visible').getByLabel('Distancia (m)', { exact: true }).inputValue(), '860')
  await page.getByRole('button', { name: 'Guardar sesión', exact: true }).click()
  assert.equal((await saved()).targetDistanceKm, 0.86)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
  assert.deepEqual(errors, [])
  console.log('Mobile + desktop: quick/structured creation, edit/reopen, running and swimming units, fractional recoveries, optional final recovery, active/passive and pace estimates, partial totals and overflow checks passed.')
} finally { await browser.close() }
